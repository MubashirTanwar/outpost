"""Export the built opening courses as one SQL script for Postgres (e.g. Supabase's SQL editor).

    python courses/build.py                                   # make sure courses.json is current
    python courses/export_sql.py > opening_courses.sql        # then paste/run it in Postgres

The script is one transaction that drops and recreates its own tables (opening_courses,
opening_chapters, opening_lines, opening_quizzes) and inserts every course, chapter, line (with
all its moves, FENs and explanations) and quiz. It touches no other table, so it is safe to run
again after any course change. Rows are readable by anyone (row level security with a read-only
policy), so a website can read them with a public key.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

SOURCE = Path(__file__).resolve().parents[1] / "backend" / "app" / "data" / "courses.json"

SCHEMA = """
drop table if exists opening_quizzes, opening_lines, opening_chapters, opening_courses cascade;

create table opening_courses (
  id          text primary key,
  position    int  not null,              -- display order
  name        text not null,
  color       text not null check (color in ('white', 'black')),
  eco         text[] not null default '{}',
  tagline     text not null default '',
  description text not null default '',
  chapters    int  not null,
  lines       int  not null,
  positions   int  not null,
  quizzes     int  not null,
  updated_at  timestamptz not null default now()
);

create table opening_chapters (
  course_id text not null references opening_courses (id) on delete cascade,
  id        text not null,
  position  int  not null,
  title     text not null,
  intro     text not null default '',
  primary key (course_id, id)
);

-- One row per line (variation). moves: [{san, uci, fen (after the move), note}], from the start position.
create table opening_lines (
  course_id  text not null,
  id         text not null,
  chapter_id text not null,
  position   int  not null,
  name       text not null,
  moves      jsonb not null,
  plies      int  not null,
  primary key (course_id, id),
  foreign key (course_id, chapter_id) references opening_chapters (course_id, id) on delete cascade
);

-- ply = half-moves already played in the line when the question is asked; fen = that position.
create table opening_quizzes (
  course_id   text not null,
  id          text not null,
  chapter_id  text not null,
  line_id     text not null,
  ply         int  not null,
  question    text not null,
  answer      text not null,
  wrong       text[] not null,
  explanation text not null default '',
  fen         text not null,
  primary key (course_id, id),
  foreign key (course_id, line_id) references opening_lines (course_id, id) on delete cascade
);

create index opening_lines_chapter on opening_lines (course_id, chapter_id, position);
"""

POLICIES = "".join(
    f"alter table {t} enable row level security;\n"
    f"create policy \"{t} are public\" on {t} for select using (true);\n"
    for t in ("opening_courses", "opening_chapters", "opening_lines", "opening_quizzes")
)


def lit(value) -> str:
    """A SQL literal."""
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, (list, tuple)):
        return "array[" + ", ".join(lit(v) for v in value) + "]::text[]" if value else "'{}'::text[]"
    return "'" + str(value).replace("'", "''") + "'"


def jsonb(value) -> str:
    return lit(json.dumps(value, ensure_ascii=False, separators=(",", ":"))) + "::jsonb"


def export(courses: list[dict]) -> str:
    out = ["-- Generated by courses/export_sql.py from courses/*.course. Do not edit by hand.", "begin;", SCHEMA]
    for ci, c in enumerate(courses):
        s = c["stats"]
        eco = c["eco"].split() if isinstance(c.get("eco"), str) else list(c.get("eco") or [])
        out.append(
            "insert into opening_courses (id, position, name, color, eco, tagline, description, chapters, lines, positions, quizzes) values ("
            + ", ".join(lit(v) for v in (c["id"], ci, c["name"], c["color"], eco, c.get("tagline", ""), c.get("description", ""),
                                         s["chapters"], s["lines"], s["positions"], s["quizzes"]))
            + ");"
        )
        for hi, ch in enumerate(c["chapters"]):
            out.append(
                "insert into opening_chapters (course_id, id, position, title, intro) values ("
                + ", ".join(lit(v) for v in (c["id"], ch["id"], hi, ch["title"], ch.get("intro", ""))) + ");"
            )
        position = 0
        for ch in c["chapters"]:
            for ln in ch["lines"]:
                moves = [{k: m.get(k) for k in ("san", "uci", "fen", "note")} for m in ln["moves"]]
                out.append(
                    "insert into opening_lines (course_id, id, chapter_id, position, name, moves, plies) values ("
                    + ", ".join([lit(c["id"]), lit(ln["id"]), lit(ch["id"]), lit(position), lit(ln["name"]), jsonb(moves), lit(len(moves))])
                    + ");"
                )
                position += 1
        for ch in c["chapters"]:
            for q in ch["quizzes"]:
                out.append(
                    "insert into opening_quizzes (course_id, id, chapter_id, line_id, ply, question, answer, wrong, explanation, fen) values ("
                    + ", ".join(lit(v) for v in (c["id"], q["id"], ch["id"], q["line"], q["ply"], q["question"], q["answer"],
                                                 q["wrong"], q.get("explanation", ""), q["fen"]))
                    + ");"
                )
    out.append(POLICIES)
    out.append("commit;")
    out.append(
        "\n-- Check: one row per course with its counts.\n"
        "select c.id, c.name, count(distinct l.id) as lines, count(distinct q.id) as quizzes\n"
        "from opening_courses c left join opening_lines l on l.course_id = c.id left join opening_quizzes q on q.course_id = c.id\n"
        "group by c.id, c.name, c.position order by c.position;"
    )
    return "\n".join(out) + "\n"


def main() -> int:
    courses = json.loads(SOURCE.read_text())["courses"]
    sys.stdout.write(export(courses))
    return 0


if __name__ == "__main__":
    sys.exit(main())
