"""Fit 'typical ACPL at each rating' per time class from collect.py rows; prints the JSON table.

    python scripts/game_rating/fit.py games.csv "Lichess 2026-10" > web/src/lib/gameRatingTable.ts
"""
import csv, json, math, statistics as st, sys
from collections import defaultdict

MIN_MOVES = 10
CLASSES = {"bullet": "bullet", "blitz": "blitz", "rapid": "rapid", "classical": "classical", "correspondence": "classical"}
ACPL_FLOOR = 5  # log scale: a near-perfect game counts as 5
rows = defaultdict(list)
allrows = defaultdict(list)
for tc, r, a, n in csv.reader(open(sys.argv[1])):
    if tc in CLASSES:
        allrows[CLASSES[tc]].append((int(r), float(a), int(n)))
        if int(n) >= MIN_MOVES:
            rows[CLASSES[tc]].append((int(r), float(a), int(n)))

table = {}
for tc, data in sorted(rows.items()):
    bins = defaultdict(list)
    for r, a, n in data:
        bins[round(r / 100) * 100].append(a)
    pts = [(b, st.median(v), len(v)) for b, v in sorted(bins.items()) if len(v) >= 150]
    # Pool adjacent violators: typical ACPL must fall as rating rises.
    blocks = [[b, m, c] for b, m, c in pts]
    i = 0
    while i < len(blocks) - 1:
        if blocks[i + 1][1] > blocks[i][1]:
            w = blocks[i][2] + blocks[i + 1][2]
            m = (blocks[i][1] * blocks[i][2] + blocks[i + 1][1] * blocks[i + 1][2]) / w
            blocks[i][1] = blocks[i + 1][1] = m
            blocks[i][2] = blocks[i + 1][2] = w
            i = max(i - 1, 0)
        else:
            i += 1
    table[tc] = [[b, round(m, 1)] for b, m, _ in blocks]
    print(f"{tc}: {len(data)} player-games, bins {pts[0][0]}..{pts[-1][0]}", file=sys.stderr)
    for b, m, c in pts:
        print(f"  {b:5d}  median ACPL {m:6.1f}  n={c}", file=sys.stderr)
# How far one game's ACPL strays from the median for its rating: per game length (moves past the
# book, in buckets of 5), the median offset and a robust sigma of log(ACPL).
def med_at(tc, r):
    pts = table[tc]
    if r <= pts[0][0]:
        return pts[0][1]
    if r >= pts[-1][0]:
        return pts[-1][1]
    for (a, x), (b, y) in zip(pts, pts[1:]):
        if a <= r <= b:
            return x + (y - x) * (r - a) / (b - a)

noise = {}
for tc, data in allrows.items():
    by_n = defaultdict(list)
    for r, a, n in data:
        by_n[min(max(n, 5) // 5 * 5, 60)].append(math.log(max(a, ACPL_FLOOR)) - math.log(med_at(tc, r)))
    out = []
    for b in sorted(by_n):
        v = by_n[b]
        if len(v) >= 200:
            q = st.quantiles(v, n=4)
            out.append([b, round(st.median(v), 3), round((q[2] - q[0]) / 1.349, 3)])
    noise[tc] = out

source = sys.argv[2] if len(sys.argv) > 2 else "Lichess"
print("// Generated by scripts/game_rating/fit.py; don't edit by hand.")
print(f"// Median ACPL of players at each rating (games with {MIN_MOVES}+ moves past the book). Source: {source}.")
print("export const GAME_RATING_TABLE: Record<\"bullet\" | \"blitz\" | \"rapid\" | \"classical\", [number, number][]> = " + json.dumps(table) + ";")
print("// Per game length (moves past the book, buckets of 5): [bucket, median offset, sigma] of log(ACPL) around the table.")
print("export const GAME_RATING_NOISE: Record<\"bullet\" | \"blitz\" | \"rapid\" | \"classical\", [number, number, number][]> = " + json.dumps(noise) + ";")
print(f"export const ACPL_FLOOR = {ACPL_FLOOR};")
